"""DEL-18 independent exact global Jacobian and Katz-open tests.

The true restricted section is G=alpha*x²+x*y+beta*y²+p*x+q*y+c.
Its global Bézout witness is a polynomial identity in Z[x,y]; when
E!=0 in a field, multiplication by E^-1 makes 1 an explicit member
of the Jacobian ideal generated by G,Gx,Gy.
"""
import unittest

from tests.test_deligne17_parabola_bad_locus import (
    FIELDS, freeze, quadratic, grad_x, grad_y,
)


def eliminant(f, a, b, p, q, c):
    return ((4*a*b-1)*c-a*q*q-b*p*p+p*q) % f


def global_unit_witness(f, a, b, p, q, c, x, y):
    e = eliminant(f, a, b, p, q, c)
    if e == 0:
        raise ValueError("unit witness needs nonzero eliminant")
    d = (4*a*b-1) % f
    g = quadratic(f, a, b, p, q, c, x, y)
    gx = grad_x(f, a, p, x, y)
    gy = grad_y(f, b, q, x, y)
    numerator = (d*g-a*gy*gy-b*gx*gx+gx*gy) % f
    return (pow(e,-1,f)*numerator) % f


class GlobalJacobianOracle(unittest.TestCase):
    def test_unit_witness_in_every_tested_field(self):
        for f in FIELDS:
            sample = [r for r in freeze() if r["eliminant"] % f != 0]
            for row in sample:
                a,b,p,q,c = (row[z]%f for z in ("alpha","beta","p","q","c"))
                e = eliminant(f,a,b,p,q,c)
                if e == 0:
                    continue
                for x in range(f):
                    for y in range(f):
                        self.assertEqual(
                            global_unit_witness(f,a,b,p,q,c,x,y),
                            1,(f,row,x,y),
                        )

    def test_unit_implies_no_critical_section(self):
        for f in FIELDS:
            for row in freeze():
                a,b,p,q,c = (row[z]%f for z in ("alpha","beta","p","q","c"))
                if eliminant(f,a,b,p,q,c):
                    self.assertFalse(any(
                        quadratic(f,a,b,p,q,c,x,y)==0 and
                        grad_x(f,a,p,x,y)==0 and
                        grad_y(f,b,q,x,y)==0
                        for x in range(f) for y in range(f)
                    ))

    def test_characteristic_two_regular_examples(self):
        f=2
        for a in range(2):
            for b in range(2):
                for p in range(2):
                    for q in range(2):
                        for c in range(2):
                            e=eliminant(f,a,b,p,q,c)
                            if e:
                                self.assertTrue(all(
                                    global_unit_witness(f,a,b,p,q,c,x,y)==1
                                    for x in range(2) for y in range(2)
                                ))

    def test_katz_principal_open_witness_with_explicit_budget(self):
        # L = alpha: a supplied principal open, serving as a *synthetic*
        # Katz-good constraint. No sheaf-theoretic Katz property is claimed.
        # coord-degree vector of E=(1,1,2,2,1);
        # coord-degree vector of L=(1,0,0,0,0).
        e_degrees=(1,1,2,2,1)
        l_degrees=(1,0,0,0,0)
        for f in (3,5,7,11):
            self.assertTrue(all(d+l<f for d,l in zip(e_degrees,l_degrees)))
            witness=(1,0,0,0,1)
            a,b,p,q,c=witness
            self.assertNotEqual(eliminant(f,a,b,p,q,c),0)
            self.assertNotEqual(a,0)

    def test_necessary_degree_condition_is_only_sufficient(self):
        # F2 violates the degree-budget hypothesis but still has
        # explicit rational parameters with nonzero E and alpha.
        self.assertFalse(2 < 2)
        self.assertNotEqual(eliminant(2,1,0,0,0,1),0)

    def test_zero_eliminant_does_not_imply_criticality(self):
        for row in freeze():
            if row["kind"]=="closure_only":
                self.assertEqual(row["eliminant"],0)
                self.assertFalse(row["has_rational_critical_point"])


if __name__=="__main__":
    unittest.main()
